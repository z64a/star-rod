/** The -DumpAudio, -BuildAudio and -VerifyAudio command line tasks. */
public abstract class AudioTasks
{
	/** Asset directory of each file type in Sbn.TYPES. */
	private static final List<String> DIRS = List.of("songs", "sfx", "bank", "per", "prg", "mseq");

	/** The files at the start of the INIT resource list, which the engine looks up by position. */
	private static final List<String> FIXED_FILES = List.of("sfx/DAT1.sef", "per/SET1.per", "prg/SET1.prg");
	private static final int RESOURCE_COUNT = 0x18;
	private static final int FIRST_AMBIENT_RESOURCE = 3;
	private static final int FIRST_RADIO_RESOURCE = 0x13;
	private static final int RADIO_BANK_RESOURCE = 0x17;

	private static final String EXTRA_FILE = "sbn_extra.bin";
	private static final int MAX_SBN_SIZE = 0x1000000;
	private static final int FORMAT_BK = 0x30;
	private static final String HEADER_COMMENT = "// Generated by Star Rod (-BuildAudio) from the audio tables. Do not edit.\n";

	private static final Key[] AUX_BANK_KEYS = { Key.bk1, Key.bk2, Key.bk3 };

	/** Whether the first command line argument names an audio task. */
	public static boolean isAudioTask(String[] args)
	{
		return args.length > 0 && switch (args[0].toUpperCase()) {
			case "-DUMPAUDIO", "-BUILDAUDIO", "-VERIFYAUDIO" -> true;
			default -> false;
		};
	}

	/**
	 * Runs the task named by args[index] and returns the number of arguments it consumed.
	 * Exits with a non-zero status if the task fails.
	 */
	public static int run(String[] args, int index)
	{
		String task = args[index].toUpperCase();
		int count = task.equals("-BUILDAUDIO") ? 1 : 2;

		try {
			if (args.length <= index + count)
				throw new IOException(args[index] + " expects " + (count == 1 ? "<out dir>" : "two arguments"));

			File first = new File(args[index + 1]);
			switch (task) {
				case "-DUMPAUDIO" -> dump(first, new File(args[index + 2]));
				case "-BUILDAUDIO" -> build(first);
				default -> verify(first, new File(args[index + 2]));
			}
		}
		catch (InputFileException e) {
			fail(e.getSourceFile(), e.getMessage());
		}
		catch (IOException e) {
			fail(null, e.getMessage());
		}
		return count;
	}

	private static void fail(File file, String message)
	{
		System.err.println(file == null ? message : file.toPath().normalize() + ": " + message);
		Environment.exit(1);
	}

	private static byte[] readFile(File file)
	{
		if (!file.isFile())
			throw new InputFileException(file, "file not found");
		try {
			return Files.readAllBytes(file.toPath());
		}
		catch (IOException e) {
			throw new InputFileException(file, e.getMessage());
		}
	}

	public static void dump(File sbnFile, File outDir) throws IOException
	{
		Sbn sbn = Sbn.read(sbnFile, readFile(sbnFile));

		File audioDir = new File(outDir, "audio");
		String[] existing = audioDir.list();
		if (existing != null && existing.length > 0)
			throw new InputFileException(audioDir, "the output directory is not empty");

		// bgm and mseq files share names in the archive, so their names start with the file index
		String[] names = new String[sbn.files.size()];
		Set<String> seen = new HashSet<>();
		for (int i = 0; i < names.length; i++) {
			Sbn.Member file = sbn.files.get(i);
			if (!file.name.matches("[A-Za-z0-9_-]+"))
				throw new InputFileException(sbnFile, "file %d has an invalid name '%s'", i, file.name);

			boolean numbered = file.type.equals("BGM") || file.type.equals("MSEQ");
			names[i] = (numbered ? String.format("%02X_", i) : "") + file.name + "." + file.type.toLowerCase();
			if (!seen.add(names[i]))
				throw new InputFileException(sbnFile, "file %d has the same name as another file: %s", i, names[i]);

			String dir = DIRS.get(Sbn.TYPES.indexOf(file.type));
			FileUtils.writeByteArrayToFile(new File(new File(audioDir, dir), names[i]), file.data);
		}

		if (sbn.extra.length > 0)
			FileUtils.writeByteArrayToFile(new File(audioDir, EXTRA_FILE), sbn.extra);

		dumpSongs(sbnFile, sbn, names, new File(audioDir, "Songs.xml"));
		dumpBanks(sbnFile, sbn, names, new File(audioDir, "Banks.xml"));
		dumpAmbient(sbnFile, sbn, names, new File(audioDir, "AmbientSounds.xml"));
	}

	private static String nameOf(File sbnFile, Sbn sbn, String[] names, int file, String type)
	{
		if (!sbn.files.get(file).type.equals(type))
			throw new InputFileException(sbnFile, "file %d is used as a %s file but is not one", file, type);
		return names[file];
	}

	private static void dumpSongs(File sbnFile, Sbn sbn, String[] names, File out) throws IOException
	{
		try (XmlWriter xmw = new XmlWriter(out)) {
			XmlTag list = xmw.createTag(Key.SongList, false);
			xmw.openTag(list);
			for (int id = 0; id < sbn.songs.size(); id++) {
				int[] song = sbn.songs.get(id);
				XmlTag tag = xmw.createTag(Key.Song, true);
				xmw.addHex(tag, Key.id, "%02X", id);
				xmw.addAttribute(tag, Key.name, AudioNames.getSongName(id));
				xmw.addAttribute(tag, Key.bgm, nameOf(sbnFile, sbn, names, song[0], "BGM"));
				for (int i = 0; i < AUX_BANK_KEYS.length; i++) {
					if (song[i + 1] != 0)
						xmw.addAttribute(tag, AUX_BANK_KEYS[i], nameOf(sbnFile, sbn, names, song[i + 1], "BK"));
				}
				xmw.printTag(tag);
			}
			xmw.closeTag(list);
			xmw.save();
		}
	}

	private static void dumpBanks(File sbnFile, Sbn sbn, String[] names, File out) throws IOException
	{
		try (XmlWriter xmw = new XmlWriter(out)) {
			XmlTag list = xmw.createTag(Key.BankList, false);
			xmw.openTag(list);
			for (int[] bank : sbn.banks) {
				XmlTag tag = xmw.createTag(Key.Bank, true);
				xmw.addAttribute(tag, Key.name, nameOf(sbnFile, sbn, names, bank[0], "BK"));
				xmw.addHex(tag, Key.group, bank[2]);
				xmw.addHex(tag, Key.index, bank[1]);
				xmw.printTag(tag);
			}
			xmw.closeTag(list);
			xmw.save();
		}
	}

	private static void dumpAmbient(File sbnFile, Sbn sbn, String[] names, File out) throws IOException
	{
		if (sbn.resources.size() != RESOURCE_COUNT)
			throw new InputFileException(sbnFile, "the INIT resource list has %d entries, expected %d",
				sbn.resources.size(), RESOURCE_COUNT);
		for (int i = 0; i < FIXED_FILES.size(); i++) {
			int file = sbn.resources.get(i);
			if (file == Sbn.NO_FILE || !FIXED_FILES.get(i).endsWith("/" + names[file]))
				throw new InputFileException(sbnFile, "INIT resource %d must be %s", i, FIXED_FILES.get(i));
		}

		try (XmlWriter xmw = new XmlWriter(out)) {
			XmlTag root = xmw.createTag(Key.AmbientSounds, false);
			xmw.openTag(root);

			for (int id = 0; id < AudioTables.AMBIENT_SLOTS; id++) {
				int file = sbn.resources.get(FIRST_AMBIENT_RESOURCE + id);
				if (file == Sbn.NO_FILE)
					continue;
				XmlTag tag = xmw.createTag(Key.AmbientSound, true);
				xmw.addHex(tag, Key.id, "%02X", id);
				xmw.addAttribute(tag, Key.name, AudioNames.getAmbientName(id));
				xmw.addAttribute(tag, Key.mseq, nameOf(sbnFile, sbn, names, file, "MSEQ"));
				xmw.printTag(tag);
			}

			int bank = sbn.resources.get(RADIO_BANK_RESOURCE);
			if (bank != Sbn.NO_FILE) {
				XmlTag tag = xmw.createTag(Key.Radio, false);
				xmw.addHex(tag, Key.id, "%02X", AudioTables.RADIO_ID);
				xmw.addAttribute(tag, Key.name, AudioNames.getAmbientName(AudioTables.RADIO_ID));
				xmw.addAttribute(tag, Key.bank, nameOf(sbnFile, sbn, names, bank, "BK"));
				xmw.openTag(tag);
				for (int player = 0; player < AudioTables.RADIO_STATIONS; player++) {
					XmlTag station = xmw.createTag(Key.Station, true);
					xmw.addInt(station, Key.player, player);
					xmw.addAttribute(station, Key.mseq,
						nameOf(sbnFile, sbn, names, sbn.resources.get(FIRST_RADIO_RESOURCE + player), "MSEQ"));
					xmw.printTag(station);
				}
				xmw.closeTag(tag);
			}

			xmw.closeTag(root);
			xmw.save();
		}
	}

	public static void build(File outDir) throws IOException
	{
		AudioLayers layers = AudioLayers.fromEnvironment();
		layers.checkTables();

		Song[] songs = AudioTables.readSongs(layers);
		List<Bank> banks = AudioTables.readBanks(layers);
		Ambient ambient = AudioTables.readAmbient(layers);

		Sbn sbn = new Sbn();
		Map<String, Integer> index = readFiles(layers, sbn);

		File extra = layers.getFile(EXTRA_FILE);
		if (extra != null)
			sbn.extra = readFile(extra);

		for (Song song : songs) {
			int[] entry = new int[4];
			entry[0] = find(sbn, index, song.source(), "song " + song.name(), song.bgm(), "BGM");
			for (int i = 0; i < AUX_BANK_KEYS.length; i++) {
				if (song.bk()[i] != null)
					entry[i + 1] = find(sbn, index, song.source(), "song " + song.name(), song.bk()[i], "BK");
			}
			sbn.songs.add(entry);
		}

		for (Bank bank : banks) {
			int file = find(sbn, index, bank.source(), "bank " + bank.file(), bank.file(), "BK");
			sbn.banks.add(new int[] { file, bank.index(), bank.group() });
		}

		for (String fixed : FIXED_FILES) {
			String name = fixed.substring(fixed.indexOf('/') + 1);
			if (!index.containsKey(name))
				throw new InputFileException(new File(fixed), "required file is missing");
			sbn.resources.add(index.get(name));
		}
		for (int i = FIXED_FILES.size(); i < RESOURCE_COUNT; i++)
			sbn.resources.add(Sbn.NO_FILE);

		for (var sound : ambient.sounds) {
			if (sound != null)
				sbn.resources.set(FIRST_AMBIENT_RESOURCE + sound.id(),
					find(sbn, index, sound.source(), "ambient sound " + sound.name(), sound.mseq(), "MSEQ"));
		}
		if (ambient.radio != null) {
			var radio = ambient.radio;
			for (int i = 0; i < AudioTables.RADIO_STATIONS; i++)
				sbn.resources.set(FIRST_RADIO_RESOURCE + i,
					find(sbn, index, radio.source(), "radio " + radio.name(), radio.mseq()[i], "MSEQ"));
			sbn.resources.set(RADIO_BANK_RESOURCE,
				find(sbn, index, radio.source(), "radio " + radio.name(), radio.bank(), "BK"));
		}

		String songHeader = songHeader(songs);
		String ambientHeader = ambientHeader(ambient);

		byte[] bytes = sbn.write();
		File sbnOut = new File(outDir, "audio.sbn");
		if (bytes.length > MAX_SBN_SIZE)
			throw new InputFileException(sbnOut, "the archive is 0x%X bytes, but the engine can address 0x%X",
				bytes.length, MAX_SBN_SIZE);

		FileUtils.forceMkdir(outDir);
		FileUtils.writeByteArrayToFile(sbnOut, bytes);
		writeIfChanged(new File(outDir, "song_ids.h"), songHeader);
		writeIfChanged(new File(outDir, "ambient_ids.h"), ambientHeader);
		writeDepfile(new File(outDir, "audio.d"), sbnOut, layers.getInputs());
	}

	/** Reads every audio file in the layers into the archive, returning file indices by file name. */
	private static Map<String, Integer> readFiles(AudioLayers layers, Sbn sbn)
	{
		Map<String, Integer> vanillaOrder = new HashMap<>();
		for (String name : AudioNames.getFileOrder()) {
			if (!name.isBlank())
				vanillaOrder.put(name.strip(), vanillaOrder.size());
		}

		record Source(int type, String name, File file)
		{}

		List<Source> sources = new ArrayList<>();
		for (int type = 0; type < DIRS.size(); type++) {
			for (String name : layers.listFiles(DIRS.get(type), "." + Sbn.TYPES.get(type).toLowerCase()))
				sources.add(new Source(type, name, layers.getFile(DIRS.get(type) + "/" + name)));
		}
		sources.sort(Comparator.comparingInt(Source::type)
			.thenComparingInt(s -> vanillaOrder.getOrDefault(s.name(), Integer.MAX_VALUE))
			.thenComparing(Source::name));

		Map<String, Integer> index = new HashMap<>();
		for (Source source : sources) {
			Sbn.Member file = Sbn.Member.read(source.file(), readFile(source.file()), 0);
			if (!file.type.equals(Sbn.TYPES.get(source.type())))
				throw new InputFileException(source.file(), "the header says %s, but the file extension says %s",
					file.type, Sbn.TYPES.get(source.type()));
			index.put(source.name(), sbn.files.size());
			sbn.files.add(file);
		}
		return index;
	}

	private static int find(Sbn sbn, Map<String, Integer> index, File source, String user, String file, String type)
	{
		Integer i = index.get(file);
		if (i == null)
			throw new InputFileException(source, "%s uses %s, which does not exist", user, file);
		if (!sbn.files.get(i).type.equals(type))
			throw new InputFileException(source, "%s uses %s, which is not a %s file", user, file, type);
		return i;
	}

	private static String songHeader(Song[] songs)
	{
		StringBuilder sb = new StringBuilder(HEADER_COMMENT).append("#pragma once\n\nenum SongIDs {\n");
		Map<String, String> owners = new HashMap<>();
		for (int id = 0; id < songs.length; id++) {
			// entries that stand in for unused IDs repeat another song's ID
			if (songs[id].id() != id || AudioNames.isUnused(songs[id].name()))
				continue;
			String name = cName("SONG_", songs[id].name(), songs[id].source(), owners);
			sb.append(String.format("    %s= 0x%08X,\n", pad(name, 32), id));
		}
		return sb.append("};\n").toString();
	}

	private static String ambientHeader(Ambient ambient)
	{
		StringBuilder sb = new StringBuilder(HEADER_COMMENT).append("#pragma once\n\nenum AmbientSounds {\n");
		Map<String, String> owners = new HashMap<>();
		for (var sound : ambient.sounds) {
			if (sound == null || AudioNames.isUnused(sound.name()))
				continue;
			String name = cName("AMBIENT_", sound.name(), sound.source(), owners);
			sb.append(String.format("    %s= %d,\n", pad(name, 24), sound.id()));
		}
		if (ambient.radio != null) {
			String name = cName("AMBIENT_", ambient.radio.name(), ambient.radio.source(), owners);
			sb.append(String.format("    %s= %d,\n", pad(name, 24), AudioTables.RADIO_ID));
		}
		return sb.append("};\n").toString();
	}

	private static String cName(String prefix, String name, File source, Map<String, String> owners)
	{
		String cName = AudioNames.toCName(prefix, name);
		String other = owners.put(cName, name);
		if (other != null)
			throw new InputFileException(source, "%s and %s both become %s", other, name, cName);
		return cName;
	}

	private static String pad(String name, int width)
	{
		return name + " ".repeat(Math.max(1, width - name.length()));
	}

	private static void writeIfChanged(File file, String content) throws IOException
	{
		byte[] bytes = content.getBytes(StandardCharsets.UTF_8);
		if (!file.isFile() || !Arrays.equals(Files.readAllBytes(file.toPath()), bytes))
			FileUtils.writeByteArrayToFile(file, bytes);
	}

	private static void writeDepfile(File depfile, File output, Set<File> inputs) throws IOException
	{
		Set<String> paths = new TreeSet<>();
		for (File input : inputs)
			paths.add(escape(input.toPath().normalize().toString()));

		StringBuilder sb = new StringBuilder(escape(output.toPath().normalize().toString())).append(":");
		for (String path : paths)
			sb.append(" \\\n  ").append(path);
		FileUtils.writeStringToFile(depfile, sb.append("\n").toString(), StandardCharsets.UTF_8);
	}

	private static String escape(String path)
	{
		return path.replace(" ", "\\ ");
	}

	/** Compares two archives byte for byte, except the size field of bank entries, which the engine does not read. */
	public static void verify(File built, File reference) throws IOException
	{
		byte[] actual = readFile(built);
		byte[] expected = readFile(reference);
		Sbn.read(built, actual);
		Sbn sbn = Sbn.read(reference, expected);

		if (actual.length != expected.length)
			throw new InputFileException(built, "the size is 0x%X, but %s is 0x%X", actual.length, reference,
				expected.length);

		ByteBuffer table = ByteBuffer.wrap(expected);
		int tableOffset = table.getInt(0x10);
		boolean[] ignored = new boolean[expected.length];
		for (int i = 0; i < sbn.files.size(); i++) {
			if ((expected[tableOffset + 8 * i + 4] & 0xFF) == FORMAT_BK)
				Arrays.fill(ignored, tableOffset + 8 * i + 5, tableOffset + 8 * i + 8, true);
		}

		int first = -1;
		int count = 0;
		for (int i = 0; i < expected.length; i++) {
			if (actual[i] != expected[i] && !ignored[i]) {
				if (first < 0)
					first = i;
				count++;
			}
		}

		if (count > 0)
			throw new InputFileException(built, "%d bytes differ from %s, the first at 0x%X (%s)", count, reference,
				first, describe(sbn, table, first));
	}

	private static String describe(Sbn sbn, ByteBuffer archive, int position)
	{
		int tableOffset = archive.getInt(0x10);
		for (int i = 0; i < sbn.files.size(); i++) {
			int offset = archive.getInt(tableOffset + 8 * i);
			if (position >= tableOffset + 8 * i && position < tableOffset + 8 * i + 8)
				return "entry " + i + " of the file table";
			if (position >= offset && position < offset + sbn.files.get(i).data.length)
				return "file " + i + ", " + sbn.files.get(i).type + " " + sbn.files.get(i).name;
		}
		return position >= archive.getInt(0x24) ? "the INIT block" : "the header";
	}
}
